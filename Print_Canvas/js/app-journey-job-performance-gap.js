  function uniq(list) {
    var seen = {};
    var out = [];
    (list || []).forEach(function (item) {
      var key = String(item || "").trim();
      if (!key || seen[key]) {
        return;
      }
      seen[key] = true;
      out.push(key);
    });
    return out;
  }

  function bankFor(elementId) {
    return BY_ELEMENT[elementId] || null;
  }

  function reasonsFor(elementId, rating, note) {
    var rate = String(rating === 2 ? 2 : 1);
    var bank = bankFor(elementId);
    var list = (bank && bank.reasons && bank.reasons[rate]) || GENERIC_REASONS[rate] || [];
    var out = [];
    if (note) {
      out.push(String(note).trim());
    }
    return uniq(out.concat(list)).slice(0, 4);
  }

  function improveFor(elementId, element) {
    var bank = bankFor(elementId);
    if (bank && bank.improve) {
      return bank.improve.slice(0, 4);
    }
    var level3 = element && element.levels && (element.levels["3"] || element.levels[3]);
    if (level3) {
      return uniq([
        String(level3).trim(),
        "انتظام التطبيق وفق مستوى الإيفاء بالتوقعات",
        "توثيق شواهد الإنجاز المرتبطة بالعنصر",
        "متابعة أثر التحسين عبر مؤشر قابل للقياس"
      ]).slice(0, 4);
    }
    return GENERIC_IMPROVE.slice(0, 4);
  }

  function strengthsFromScores(elements, ratingMap, gapElementId) {
    var ranked = (elements || [])
      .map(function (item) {
        var r = ratingMap ? ratingMap[item.id] : null;
        return { id: item.id, label: item.label || item.id, rating: r };
      })
      .filter(function (row) {
        return row.id !== gapElementId && row.rating != null && Number(row.rating) >= 4;
      })
      .sort(function (a, b) {
        return Number(b.rating) - Number(a.rating);
      });
    var out = ranked.slice(0, 3).map(function (row) {
      return "تميّز في: " + row.label + " (تقدير " + row.rating + ")";
    });
    while (out.length < 4) {
      out.push(
        [
          "يلتزم بالتعاون المهني عند تكليفه داخل الفريق",
          "يظهر استعداداً لتحسين ممارسته عند التوجيه",
          "يحافظ على تواصل أساسي مع الزملاء والإدارة",
          "ينجز جزءاً من مهامه التشغيلية بانتظام"
        ][out.length]
      );
    }
    return out.slice(0, 4);
  }

  function stepsFor(elementId) {
    var bank = bankFor(elementId);
    return ((bank && bank.steps) || GENERIC_STEPS).slice(0, 4);
  }

  function indicatorsFor(elementId) {
    var bank = bankFor(elementId);
    return ((bank && bank.indicators) || GENERIC_INDICATORS).slice(0, 4);
  }

  function evidenceFor(elementId) {
    var bank = bankFor(elementId);
    return ((bank && bank.evidence) || GENERIC_EVIDENCE).slice(0, 4);
  }

  function buildSuggestion(ctx) {
    ctx = ctx || {};
    var elementId = ctx.elementId || "";
    var rating = ctx.rating === 2 ? 2 : 1;
    var reasons = reasonsFor(elementId, rating, ctx.note);
    var improve = improveFor(elementId, ctx.element);
    var strengths = strengthsFromScores(ctx.elements, ctx.ratingMap, elementId);
    var steps = stepsFor(elementId);
    var indicators = indicatorsFor(elementId);
    var evidence = evidenceFor(elementId);
    return {
      reasons: reasons[0] || "",
      strengths: strengths[0] || "",
      improve_areas: improve[0] || "",
      action_steps: [
        {
          step: steps[0] || "",
          owner: OWNERS[0],
          when: WHEN[0],
          indicator: indicators[0] || "",
          evidence: evidence[0] || ""
        }
      ],
      options: {
        reasons: reasons,
        strengths: strengths,
        improve_areas: improve,
        step: steps,
        owner: OWNERS.slice(),
        when: WHEN.slice(),
        indicator: indicators,
        evidence: evidence
      }
    };
  }

