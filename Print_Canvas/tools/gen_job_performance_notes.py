def pack(levels: list[list[str]]) -> dict[str, list[str]]:
    assert len(levels) == 5, len(levels)
    out = {}
    for i, opts in enumerate(levels, start=1):
        assert len(opts) == 4, (i, len(opts))
        for o in opts:
            assert isinstance(o, str) and o.strip(), o
            assert len(o) <= 120, (len(o), o)
            for bad in ("ولاء", "تدخل عاجل", "متابعة يومية", "توجيههاً", "فورية"):
                assert bad not in o, (bad, o)
        out[str(i)] = opts
    return out


def check(bank: dict, name: str) -> None:
    for eid, levels in bank.items():
        for r in ("1", "2", "3", "4", "5"):
            assert r in levels, (name, eid, r)
            assert len(levels[r]) == 4, (name, eid, r)


