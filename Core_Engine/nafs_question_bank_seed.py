def all_questions() -> list[dict]:
    from .nafs_question_bank_expand150 import expand_questions
    from .nafs_wave_b_212223 import wave_b_questions

    base = build_math_questions() + build_science_questions() + build_reading_questions()
    assert len(base) == 86, len(base)
    expanded = expand_questions()
    wave_b = wave_b_questions()
    rows = base + expanded + wave_b
    # منع تكرار الجذوع بين الأساس والتوسيع والموجة ب
    seen = set()
    unique = []
    for row in rows:
        key = (row["domain"], (row["stem"] or "").strip())
        if key in seen:
            continue
        seen.add(key)
        unique.append(row)
    assert len(unique) >= EXPECTED_MIN_COUNT, len(unique)
    return unique


def _meta_get(connection, key: str) -> str:
    row = connection.execute(
        "SELECT value FROM nafs_question_bank_meta WHERE key = ? LIMIT 1",
        (key,),
    ).fetchone()
    return str(row[0]) if row and row[0] is not None else ""


def _meta_set(connection, key: str, value: str) -> None:
    connection.execute(
        """
        INSERT INTO nafs_question_bank_meta(key, value) VALUES(?, ?)
        ON CONFLICT(key) DO UPDATE SET value = excluded.value
        """,
        (key, value),
    )


def _bank_is_stale(connection, count: int) -> bool:
    if count < EXPECTED_MIN_COUNT:
        return True
    if _meta_get(connection, "revision") != BANK_REVISION:
        return True
    stem6 = connection.execute(
        "SELECT stem FROM nafs_question_bank WHERE domain = 'math' AND sort_order = 6 LIMIT 1"
    ).fetchone()
    text = (stem6[0] if stem6 else "") or ""
    # الصيغة المعتمدة بعد التدقيق: |−٨| بأرقام هندية
    if "−٨" not in text and "-٨" not in text:
        return True
    western = connection.execute(
        r"""
        SELECT COUNT(*) FROM nafs_question_bank
        WHERE COALESCE(active,1)=1
          AND domain IN ('math','science')
          AND (
            stem GLOB '*[0-9]*'
            OR choice_a GLOB '*[0-9]*'
            OR choice_b GLOB '*[0-9]*'
            OR choice_c GLOB '*[0-9]*'
            OR choice_d GLOB '*[0-9]*'
            OR rationale GLOB '*[0-9]*'
          )
        """
    ).fetchone()[0]
    if int(western or 0) > 0:
        return True
    # وجود نص توسعة القراءة علامة على اكتمال الدفعة
    expand_passage = connection.execute(
        "SELECT COUNT(*) FROM nafs_question_bank WHERE passage_id = 'p5' AND COALESCE(active,1)=1"
    ).fetchone()[0]
    if int(expand_passage or 0) < 1:
        return True
    distinct = connection.execute(
        "SELECT COUNT(DISTINCT UPPER(correct)) FROM nafs_question_bank WHERE COALESCE(active,1)=1"
    ).fetchone()[0]
    return int(distinct or 0) < 3


def ensure_nafs_question_bank(connection, force_reseed: bool = False) -> dict:
    connection.executescript(SCHEMA_SQL)
    count = connection.execute(
        "SELECT COUNT(*) FROM nafs_question_bank WHERE COALESCE(active,1)=1"
    ).fetchone()[0]
    if count >= EXPECTED_MIN_COUNT and not force_reseed and not _bank_is_stale(connection, count):
        try:
            from .nafs_misconception_lab import enrich_question_traps, ensure_question_columns

            ensure_question_columns(connection)
            enrich_question_traps(connection)
        except Exception:
            pass
        return {"ok": True, "stored": count, "seeded": False, "revision": BANK_REVISION}
    try:
        from .nafs_misconception_lab import ensure_question_columns

        ensure_question_columns(connection)
    except Exception:
        pass
    connection.execute("DELETE FROM nafs_question_bank")
    rows = all_questions()
    connection.executemany(
        """
        INSERT INTO nafs_question_bank (
            domain, skill, stem, choice_a, choice_b, choice_c, choice_d,
            correct, rationale, passage_id, passage_title, passage_text, sort_order, active,
            common_mistake, grade_root, golden_rule
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, ?, ?, ?)
        """,
        [
            (
                r["domain"],
                r["skill"],
                r["stem"],
                r["choice_a"],
                r["choice_b"],
                r["choice_c"],
                r["choice_d"],
                r["correct"],
                r["rationale"],
                r["passage_id"],
                r["passage_title"],
                r["passage_text"],
                r["sort_order"],
                r.get("common_mistake") or "",
                r.get("grade_root") or "",
                r.get("golden_rule") or "",
            )
            for r in rows
        ],
    )
    _meta_set(connection, "revision", BANK_REVISION)
    try:
        from .nafs_misconception_lab import enrich_question_traps, ensure_question_columns

        ensure_question_columns(connection)
        enrich_question_traps(connection)
    except Exception:
        pass
    return {"ok": True, "stored": len(rows), "seeded": True, "revision": BANK_REVISION}
