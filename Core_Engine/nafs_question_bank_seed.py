EASTERN = "٠١٢٣٤٥٦٧٨٩"


def _e(value) -> str:
    """تحويل الأرقام الغربية إلى هندية مع٪ — دون المساس بالرموز العلمية."""
    out = []
    for ch in str(value):
        if ch.isdigit():
            out.append(EASTERN[int(ch)])
        elif ch == "%":
            out.append("٪")
        else:
            out.append(ch)
    return "".join(out)

