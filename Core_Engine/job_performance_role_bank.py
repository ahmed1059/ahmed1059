def assert_weights(payload: dict) -> None:
    total = sum(int(item["weight"]) for item in payload["elements"])
    if total != 100:
        raise ValueError(f"{payload['role_code']}: مجموع الأوزان {total} وليس 100")


def all_extra_templates() -> list[dict]:
    out = []
    for builder in ROLE_TEMPLATE_BUILDERS.values():
        payload = builder()
        assert_weights(payload)
        out.append(payload)
    return out
