def _clone_teacher(weight_map: dict[str, int]) -> list[dict]:
    by_id = {str(item["id"]): item for item in TEACHER_ELEMENTS}
    out = []
    for eid, weight in weight_map.items():
        base = deepcopy(by_id[eid])
        base["weight"] = int(weight)
        out.append(base)
    return out


def _el(eid: str, label: str, weight: int, description: str, levels: dict) -> dict:
    return {
        "id": eid,
        "label": label,
        "weight": weight,
        "description": description,
        "levels": levels,
    }


