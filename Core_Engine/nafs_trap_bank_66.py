def _pack(domain: str, rows: list[tuple], start_idx: int) -> list[dict]:
    door = {
        "math": "أفخاخ الرياضيات",
        "science": "أفخاخ العلوم",
        "reading": "أفخاخ لغتي والقراءة",
    }[domain]
    out = []
    for i, (skill, root, mistake, rule, wrong_ex, correct_ex) in enumerate(rows):
        idx = start_idx + i
        out.append(
            {
                "id": f"trap-{domain}-{i+1}",
                "domain": domain,
                "door": door,
                "skill": skill,
                "etec": ETEC[domain],
                "grade_root": root,
                "common_mistake": mistake,
                "golden_rule": rule,
                "wrong_example": wrong_ex,
                "correct_example": correct_ex,
                "prompt": f"فخ {_e(idx)}: {skill}",
                "sort": idx,
            }
        )
    return out


def build_unique_trap_album() -> list[dict]:
    assert len(_MATH) == 22 and len(_SCIENCE) == 22 and len(_READING) == 22
    album = _pack("math", _MATH, 1) + _pack("science", _SCIENCE, 23) + _pack("reading", _READING, 45)
    assert len(album) == 66
    # ضمان عدم تكرار نص الفخ أو المثال
    mistakes = [t["common_mistake"] for t in album]
    wrongs = [t["wrong_example"] for t in album]
    assert len(mistakes) == len(set(mistakes)), "تكرار في وصف الفخ"
    assert len(wrongs) == len(set(wrongs)), "تكرار في مثال الخطأ"
    return album
