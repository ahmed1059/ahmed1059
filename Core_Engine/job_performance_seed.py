def teacher_template_payload() -> dict:
    weights = [int(item["weight"]) for item in TEACHER_ELEMENTS]
    if sum(weights) != 100:
        raise ValueError("مجموع أوزان نموذج المعلم يجب أن يساوي 100")
    return {
        "role_code": "teacher",
        "title": ROLE_CODES["teacher"],
        "source": "دليل إدارة الأداء الوظيفي لشاغلي الوظائف التعليمية — الإصدار الثاني",
        "band_labels": BAND_LABELS,
        "elements": list(TEACHER_ELEMENTS),
    }


def band_from_percent(percent: float) -> tuple[int, str]:
    value = float(percent or 0)
    for threshold, band in BAND_PERCENT_THRESHOLDS:
        if value >= threshold:
            return band, BAND_LABELS[band]
    return 1, BAND_LABELS[1]


def compute_totals(elements: list[dict], ratings: dict[str, int | None]) -> dict:
    """احتساب موزون رسمي: (تقدير × وزن) ثم النسبة = المجموع / 5."""
    weighted = 0.0
    scored = 0
    total_weight = 0.0
    for element in elements:
        eid = str(element.get("id") or "")
        weight = float(element.get("weight") or 0)
        total_weight += weight
        raw = ratings.get(eid)
        if raw is None:
            continue
        try:
            rating = int(raw)
        except (TypeError, ValueError):
            continue
        if rating < 1 or rating > 5:
            continue
        weighted += rating * weight
        scored += 1
    percent = round(weighted / 5.0, 2) if scored else 0.0
    band, label = band_from_percent(percent) if scored else (0, "")
    readiness = round((scored / len(elements)) * 100, 1) if elements else 0.0
    return {
        "weighted_sum": round(weighted, 2),
        "percent": percent,
        "band": band,
        "band_label": label,
        "scored_count": scored,
        "element_count": len(elements),
        "readiness_percent": readiness,
        "weights_total": total_weight,
    }
