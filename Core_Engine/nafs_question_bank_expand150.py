EASTERN = "٠١٢٣٤٥٦٧٨٩"


def _e(value) -> str:
    text = str(value)
    out = []
    for ch in text:
        if ch.isdigit():
            out.append(EASTERN[int(ch)])
        elif ch == "%":
            out.append("٪")
        else:
            out.append(ch)
    return "".join(out)


def _frac(num, den) -> str:
    return f"{_e(num)}/{_e(den)}"


