def canon(name: str) -> str:
    name = re.sub(r"\s+", " ", name).strip()
    return ALIASES.get(name, name)


def classify(name: str) -> str:
    for plan, keys in RULES:
        for key in keys:
            if key in name:
                return plan
    if name.startswith(("مسابقة", "نادي")):
        return "خطة رائد النشاط"
    if any(token in name for token in ("مسابقات", "أندية", "إذاعة", "رحلات", "صيفي")):
        return "خطة رائد النشاط"
    if name.startswith(("مبادرة", "برنامج", "أسبوع", "زيارة")):
        return "خطة وكيل الشؤون التعليمية"
    return "مراجعة يدوية"


def kind_of(name: str) -> str:
    if name.startswith("مبادرة"):
        return "مبادرة"
    if name.startswith("مسابقة"):
        return "مسابقة"
    if name.startswith("نادي"):
        return "نادي"
    return "برنامج"


def extract() -> list[str]:
    lines = SRC.read_text(encoding="utf-8", errors="replace").splitlines()
    found: list[str] = []
    labels = {
        "اسم البرنامج",
        "اسم البرنامج / المبادرة",
        "اسم البرنامج/المبادرة",
        "اسم المبادرة",
    }
    for index, line in enumerate(lines):
        text = line.strip()
        if text in labels and index + 1 < len(lines):
            nxt = lines[index + 1].strip()
            if (
                nxt
                and 4 <= len(nxt) <= 120
                and nxt not in NOISE
                and not nxt.startswith(("تاريخ", "المنفذ", "المشارك", "مكان", "مدة", "إدارة"))
            ):
                found.append(nxt)
        if re.match(r"^(برنامج|مبادرة|مسابقة|نادي)\b", text) and 6 <= len(text) <= 110:
            if text not in NOISE and not re.search(r"الهدف الأول|الخطوة الأولى|يتكون من", text):
                found.append(text)
    uniq: list[str] = []
    seen: set[str] = set()
    for item in found:
        name = canon(item)
        if name in NOISE or name in seen:
            continue
        seen.add(name)
        uniq.append(name)
    return uniq


def main() -> None:
    items = extract()
    buckets = {key: [] for key in ORDER}
    for name in items:
        buckets[classify(name)].append(name)

    lines = [
        "# جدول البرامج حسب خطة المنسوب",
        "## المصدر: ملف «البرامج والتقارير والسجلات والمحاضر»",
        "## التصنيف: خطط المنسوبين (مدير · وكيلان · موجه · رائد · مساعد إداري · معلم · محضر مختبر · أمين مصادر)",
        "",
        "| م | البرنامج / المبادرة / المسابقة | النوع | خطة المنسوب |",
        "|---:|---|---|---|",
    ]
    counter = 1
    for plan in ORDER:
        for name in buckets[plan]:
            lines.append(f"| {counter} | {name} | {kind_of(name)} | {plan} |")
            counter += 1
    lines.extend(
        [
            "",
            "## ملخص العدد",
            "",
            "| خطة المنسوب | العدد |",
            "|---|---:|",
        ]
    )
    total = 0
    for plan in ORDER:
        count = len(buckets[plan])
        if count:
            lines.append(f"| {plan} | {count} |")
            total += count
    lines.append(f"| **الإجمالي** | **{total}** |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} total={total}")
    for plan in ORDER:
        print(plan, len(buckets[plan]))


if __name__ == "__main__":
    main()
